-- 2026-06-10 — заміна попереднього бекфілу (0042). Замість розкиду по реальним
-- датам work_start / docs / arrival, всі ІСНУЮЧІ кандидати отримують флаг-дату
-- 2026-01-01 — це чіткий маркер «імпортовано з xlsx сьогодні, історичні дані».
--
-- Майбутні INSERT'и природньо отримають NOW() через DEFAULT, тому ця міграція
-- ні на що нове не вплине — тільки на 464 рядки, які зараз у таблиці.
--
-- Логіка: WHERE created_at < '2026-06-11' — захист на випадок, якщо хтось
-- встиг створити реального нового кандидата між моментом створення цієї
-- міграції і її застосуванням. Дата 2026-06-11 = завтра, тому будь-який
-- created_at сьогодні (2026-06-10) підпадає.

UPDATE candidates
SET created_at = '2026-01-01T00:00:00Z'::timestamptz
WHERE created_at < '2026-06-11T00:00:00Z'::timestamptz;
